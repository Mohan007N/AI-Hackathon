"""
Pydantic schemas for agent execution endpoints and LLM task plans.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any, Optional
from pydantic import BaseModel, Field


class SubGoal(BaseModel):
    """Structured milestone subgoal for multi-goal checklist tracking (Issue D)."""
    id: str = Field(..., description="Unique subgoal ID, e.g. 'subgoal_1'")
    description: str = Field(..., description="Description of the subgoal")
    required: bool = Field(True, description="Whether this subgoal is mandatory for task completion")
    completed: bool = Field(False, description="Whether this subgoal has been verified as accomplished")
    verification_evidence: Optional[str] = Field(None, description="Evidence confirming completion")


class TaskPlan(BaseModel):
    """Structured plan generated by NLU / LLM from student's request."""
    intent: str = Field(..., description="Categorized user intent, e.g. 'register_elective'")
    goal: str = Field(..., description="High-level goal description")
    constraints: list[str] = Field(default_factory=list, description="Extracted constraints, e.g. ['open_elective']")
    steps: list[str] = Field(default_factory=list, description="Logical milestone steps")
    subgoals: list[SubGoal] = Field(default_factory=list, description="Structured goal checklist for multi-step verification")
    actions: list[str] = Field(default_factory=list, description="Whitelisted browser action keywords")
    needs_clarification: bool = Field(False, description="Whether the prompt is too ambiguous")
    clarification_prompt: Optional[str] = Field(None, description="Question to ask user if clarification needed")


class StepActionDecision(BaseModel):
    """Decision produced by the agent reasoning loop for the next action."""
    action_type: str = Field(..., description="Action from ALLOWED_ACTION_TYPES")
    target_element: Optional[str] = Field(None, description="Semantic description, text, or element_id (e.g. elem_1)")
    target_value: Optional[str] = Field(None, description="Input value for forms (never credentials)")
    reasoning: str = Field(..., description="Justification for this action")
    is_irreversible: bool = Field(False, description="Whether this action requires human confirmation")
    is_task_complete: bool = Field(False, description="Whether the goal has been achieved")
    subgoal_id_completed: Optional[str] = Field(None, description="ID of subgoal completed by this action, if any")


class AgentExecuteRequest(BaseModel):
    run_id: str = Field(..., description="Run ID returned by /api/task/start")

    model_config = {"json_schema_extra": {"example": {"run_id": "run_abc123"}}}


class ActionLogEntry(BaseModel):
    t: str                           # ISO-8601 timestamp
    step: int
    action: str
    target: Optional[str] = None
    url: Optional[str] = None
    value: Optional[Any] = None
    reason: Optional[str] = None
    result: Optional[str] = None


class AgentStatusResponse(BaseModel):
    run_id: str
    status: str    # "started" | "running" | "awaiting_approval" | "done" | "not_done" | "error"
    current_action: Optional[str] = None
    step: Optional[int] = None
    progress: Optional[str] = None
    result_summary: Optional[str] = None
    error: Optional[str] = None
    updated_at: datetime = Field(default_factory=datetime.now)


class AgentLogsResponse(BaseModel):
    run_id: str
    entries: list[ActionLogEntry]
    count: int

